@app.route("/api/traces", methods=["GET"])
def get_traces():
    summary = parse_trace_summary()
    events = parse_trace_filtered()
    return jsonify({
        "summary": summary,
        "events": events[-50:],  # Return latest 50 events
        "errors": [e for e in events if e["is_error"]]
    })

@app.route("/api/run/<action>", methods=["POST"])
def run_action(action):
    command_map = {
        "build": "make clean && make all",
        "batch": "./sys_call_demo --batch",
        "file": "./sys_call_demo --file",
        "process": "./sys_call_demo --process",
        "error": "./sys_call_demo --error",
        "test": "make test",
        "trace": "make trace",
        "analyze": "make analyze",
        "clean": "make clean"
    }

    if action not in command_map:
        return jsonify({"success": False, "error": f"Invalid action '{action}'"}), 400

    cmd = command_map[action]
    code, output = run_project_command(cmd)

    # Clean ANSI escape sequences for web rendering (or keep them for terminal viewer)
    clean_output = output

    # Fetch updated trace stats if trace or analyze was run
    traces_data = None
    if action in ["batch", "trace", "analyze", "test"]:
        traces_data = {
            "summary": parse_trace_summary(),
            "events": parse_trace_filtered()[-30:]
        }

    return jsonify({
        "success": (code == 0),
        "return_code": code,
        "command": cmd,
        "output": clean_output,
        "traces": traces_data
    })

